// node --test scripts/jira/test/description.test.mjs
import test from "node:test";
import assert from "node:assert/strict";
import { md2adf, build, originalNodes, inline } from "../description.mjs";

const doc = (...content) => ({ type: "doc", version: 1, content });
const p = (t) => ({ type: "paragraph", content: [{ type: "text", text: t }] });
const h = (t, level = 2) => ({ type: "heading", attrs: { level }, content: [{ type: "text", text: t }] });
const texts = (n) => (n.text || "") + (n.content || []).map(texts).join("");

const SAMPLE = `_Generated by AI agent on 2026-10-11. Work type: Apex change. Pending human review._

### Business Context

Sales users need a **fast** view.

### Scope

* In scope:
    * Add a component.
    * Handle \`loading\` states.
* Out of scope:
    * New objects.

### Technical Notes

See [the guide](docs/guide.md) and [Salesforce](https://developer.salesforce.com).

1. First
2. Second

---
`;

test("headings, paragraphs and marks", () => {
  const d = md2adf(SAMPLE, "https://github.com/o/r/blob/main/");
  assert.equal(d.content[0].type, "paragraph");
  assert.deepEqual(d.content[0].content[0].marks, [{ type: "em" }]);
  assert.deepEqual(d.content[1], h("Business Context", 3));
  const strong = d.content[2].content.find((n) => n.text === "fast");
  assert.deepEqual(strong.marks, [{ type: "strong" }]);
});

test("nested bullet lists", () => {
  const list = md2adf(SAMPLE).content.find((n) => n.type === "bulletList");
  assert.equal(list.content.length, 2);
  const inner = list.content[0].content[1];
  assert.equal(inner.type, "bulletList");
  assert.equal(inner.content.length, 2);
  assert.equal(texts(inner.content[1]), "Handle loading states.");
});

test("ordered list, rule and links (relative made absolute)", () => {
  const d = md2adf(SAMPLE, "https://github.com/o/r/blob/main/");
  assert.ok(d.content.some((n) => n.type === "orderedList" && n.content.length === 2));
  assert.equal(d.content[d.content.length - 1].type, "rule");
  const links = JSON.stringify(d).match(/"href":"[^"]+"/g);
  assert.deepEqual(links, ['"href":"https://github.com/o/r/blob/main/docs/guide.md"', '"href":"https://developer.salesforce.com"']);
});

test("snake_case words are not italic", () => {
  assert.deepEqual(inline("use account_health_c field"), [{ type: "text", text: "use account_health_c field" }]);
});

test("code block", () => {
  const d = md2adf("```apex\nSystem.debug(1);\n```");
  assert.deepEqual(d.content[0], { type: "codeBlock", attrs: { language: "apex" }, content: [{ type: "text", text: "System.debug(1);" }] });
});

test("no empty text nodes anywhere", () => {
  assert.ok(!JSON.stringify(md2adf(SAMPLE)).includes('"text":""'));
});

test("first run wraps the original story", () => {
  const out = build(doc(p("Sales want a health preview.")), SAMPLE);
  assert.deepEqual(out.content.slice(0, 4).map((n) => n.type), ["heading", "paragraph", "rule", "heading"]);
  assert.equal(texts(out.content[0]), "Original Story");
  assert.equal(texts(out.content[1]), "Sales want a health preview.");
  assert.equal(texts(out.content[3]), "AI Enrichment");
});

test("rework replaces the enrichment, never duplicates it", () => {
  const once = build(doc(p("Story text.")), SAMPLE);
  const twice = build(once, "### Business Context\n\nRevised.");
  assert.equal(JSON.stringify(twice).match(/Original Story/g).length, 1);
  assert.equal(JSON.stringify(twice).match(/AI Enrichment/g).length, 1);
  assert.ok(JSON.stringify(twice).includes("Revised."));
  assert.ok(!JSON.stringify(twice).includes("Sales users need"));
  assert.deepEqual(originalNodes(twice), [p("Story text.")]);
});

test("rich original content is preserved exactly", () => {
  const table = { type: "table", content: [] };
  const out = build(doc(p("a"), table, p("b")), "x");
  assert.deepEqual(out.content.slice(1, 4), [p("a"), table, p("b")]);
});

test("empty description gets a placeholder", () => {
  assert.equal(texts(build(null, "x").content[1]), "(No description was provided.)");
});

test("agent-repeated section heading is dropped", () => {
  const out = build(null, "## AI Enrichment\n\nBody");
  assert.equal(JSON.stringify(out).match(/AI Enrichment/g).length, 1);
});
